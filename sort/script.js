// デフォルトの順序
const letters = ["b", "A", "a", "B"];

letters.sort();

console.log(letters);

// 例：文字列を並び替える
const fruits = ["banana", "apple", "cherry", "orange"];

fruits.sort();

console.log(fruits);

// 例：数値を並び替える
const numbers = [30, 5, 100, 20, 8];

numbers.sort();

console.log(numbers);
